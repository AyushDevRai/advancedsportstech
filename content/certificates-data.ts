export function getCompactStandardBadge(standard: string, governingBody: string): string {
  if (governingBody === "FIH") {
    if (standard.includes("Cat 1") || standard.includes("Category 1") || standard.includes("World Cup")) {
      return "FIH Category 1";
    }
    if (standard.includes("Global")) {
      return "FIH Global";
    }
    return "FIH Certified";
  }

  if (governingBody.includes("Athletics") || governingBody === "IAAF") {
    if (standard.includes("Class 2") || standard.includes("CLASS-2")) {
      return "WA Class 2";
    }
    return "World Athletics";
  }

  if (standard.toLowerCase().includes("class 2") || standard.toLowerCase().includes("class-2")) {
    return "Class 2 Track";
  }

  return standard.length > 18 ? standard.slice(0, 16) + "…" : standard;
}
